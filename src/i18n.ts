// src/i18n.ts

export type SupportedLang = 'en' | 'fr' | 'es';
export type SupportedCurrency = 'EUR' | 'USD' | 'GBP' | 'CHF';

export const CURRENCIES: { code: SupportedCurrency; symbol: string; label: string }[] = [
  { code: 'EUR', symbol: '€', label: 'EUR (€)' },
  { code: 'USD', symbol: '$', label: 'USD ($)' },
  { code: 'GBP', symbol: '£', label: 'GBP (£)' },
  { code: 'CHF', symbol: 'CHF', label: 'CHF' }
];

export const detectBrowserLanguage = (): SupportedLang => {
  if (typeof window === 'undefined') return 'en';
  const saved = localStorage.getItem('whatif_lang') as SupportedLang;
  if (saved && ['en', 'fr', 'es'].includes(saved)) return saved;

  const browserLang = (navigator.language || '').toLowerCase();
  if (browserLang.startsWith('fr')) return 'fr';
  if (browserLang.startsWith('es')) return 'es';
  return 'en';
};

export const detectStoredCurrency = (): SupportedCurrency => {
  if (typeof window === 'undefined') return 'EUR';
  const saved = localStorage.getItem('whatif_currency') as SupportedCurrency;
  if (saved && ['EUR', 'USD', 'GBP', 'CHF'].includes(saved)) return saved;
  return 'EUR';
};

export const formatCurrency = (amount: number, currency: SupportedCurrency = 'EUR', lang: SupportedLang = 'en'): string => {
  if (!isFinite(amount) || isNaN(amount)) return '—';
  try {
    return new Intl.NumberFormat(lang === 'fr' ? 'fr-FR' : lang === 'es' ? 'es-ES' : 'en-US', {
      style: 'currency',
      currency,
      maximumFractionDigits: 0
    }).format(amount);
  } catch {
    const symbol = CURRENCIES.find(c => c.code === currency)?.symbol || currency;
    return `${Math.round(amount).toLocaleString()} ${symbol}`;
  }
};

export const formatNumber = (val: number, lang: SupportedLang = 'en'): string => {
  if (!isFinite(val) || isNaN(val)) return '0';
  return new Intl.NumberFormat(lang === 'fr' ? 'fr-FR' : lang === 'es' ? 'es-ES' : 'en-US', {
    maximumFractionDigits: 1
  }).format(val);
};

